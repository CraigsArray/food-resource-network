/**
 * syncSdFoodBank.js
 *
 * Fetches food distribution locations from the San Diego Food Bank's Storepoint API,
 * filters to East County ZIP codes, parses schedules (deterministically where possible,
 * GPT-4o-mini as a fallback), and upserts them as draft posts in Supabase.
 *
 * Run:  node scripts/syncSdFoodBank.js
 *
 * Required environment variables (GitHub Secrets → injected by Actions):
 *   SUPABASE_URL              — Supabase project URL
 *   SUPABASE_SERVICE_ROLE_KEY — service role key (bypasses RLS)
 *   OPENAI_API_KEY            — GPT-4o-mini for schedule parsing
 *
 * One-time Supabase setup (run once in SQL Editor before first sync):
 *   INSERT INTO organizations (name, domain, is_verified)
 *   VALUES ('San Diego Food Bank', 'sandiegofoodbank.org', true)
 *   ON CONFLICT (domain) DO UPDATE SET name = 'San Diego Food Bank', is_verified = true;
 *
 * IMPORTANT — Timezone:
 *   All locations are in San Diego (America/Los_Angeles). GitHub Actions runners
 *   default to UTC, which shifts "today" and weekday math by several hours and
 *   can push calculations onto the wrong calendar day. Set TZ in the workflow
 *   YAML as the primary fix:
 *
 *     jobs:
 *       sync:
 *         runs-on: ubuntu-latest
 *         env:
 *           TZ: America/Los_Angeles
 *
 *   The line below is a belt-and-suspenders backup in case TZ isn't set in the
 *   workflow. It must run before any Date object is created.
 *
 * Note on source_ids and the sync window:
 *   Each run generates a post for every occurrence of a location's schedule
 *   from right now through one month out (see computeWindowEnd) — not just
 *   the single next occurrence. Since this runs on the 1st and 15th, the two
 *   windows overlap by design (1st → next 1st; 15th → next 15th), so the same
 *   specific occurrence is often regenerated by both runs. source_ids include
 *   the occurrence's date (e.g. `sdfb_<id>_thursday_1st_20260806`) so a
 *   repeated occurrence lands on the same row and gets updated, not
 *   duplicated. deactivateVanished() checks at the location level (parsing
 *   the location id back out of source_id), not the exact source_id, since a
 *   post whose date has simply passed out of the window is expected to stop
 *   reappearing without that meaning its location vanished from Storepoint.
 */


/**
 * Splits a Storepoint address string into { address, city, zip }.
 * Handles both formats:
 *   "1234 Main St, El Cajon, CA 92020, US"  (Feeding SD style)
 *   "1234 Main St, El Cajon, CA 92020"       (SDFB style — no trailing ", US")
 */
function parseAddress(full) {
  const match = full?.trim().match(
    /^(.+?),\s*([^,]+),\s*([A-Z]{2})\s+(\d{5}(?:-\d{4})?),?\s*(?:US)?$/i
  )
  if (!match) return { address: full ?? '', city: '', zip: '' }
  return { address: match[1].trim(), city: match[2].trim(), zip: match[4].trim() }
}

/** Safely parses the Storepoint custom_fields JSON string. */
function parseCustomFields(str) {
  if (!str) return {}
  try { return JSON.parse(str) } catch { return {} }
}

/**
 * Normalises and capitalises a comma-separated tag string.
 * Storepoint for SDFB uses lowercase tags like "thursday,neighborhood distribution".
 */
function normaliseTags(tagStr) {
  if (!tagStr) return []
  return tagStr
    .split(',')
    .map(t => t.trim())
    .filter(Boolean)
    .map(t => t.charAt(0).toUpperCase() + t.slice(1))
}

/**
 * Parses a "H:MM AM/PM" or hour-only "H AM/PM" time string (space before am/pm
 * optional). Real SDFB data mixes both — "10:00am" and plain "11 AM" appear
 * in the same field set. Returns { hour, minute } or null.
 */
function parseSingleTime(str) {
  const m = str.trim().match(/^(\d{1,2})(?::(\d{2}))?\s*(AM|PM)$/i)
  if (!m) return null
  let h = parseInt(m[1])
  const min = m[2] ? parseInt(m[2]) : 0
  const ampm = m[3].toUpperCase()
  if (ampm === 'PM' && h !== 12) h += 12
  if (ampm === 'AM' && h === 12) h = 0
  return { hour: h, minute: min }
}

/**
 * Returns the Date of the Nth (or last) occurrence of a given weekday within
 * a specific year/month, or null if that ordinal doesn't exist in that month
 * (e.g. a "5th Thursday" that doesn't occur).
 */
function nthWeekdayOfMonth(year, month, weekdayIndex, ordinal) {
  if (ordinal === 'last') {
    const last = new Date(year, month + 1, 0) // last calendar day of month
    const diff = (last.getDay() - weekdayIndex + 7) % 7
    last.setDate(last.getDate() - diff)
    return last
  }
  const first = new Date(year, month, 1)
  const firstWeekday = first.getDay()
  const dayOffset = (weekdayIndex - firstWeekday + 7) % 7
  const date = 1 + dayOffset + (ordinal - 1) * 7
  const result = new Date(year, month, date)
  if (result.getMonth() !== month) return null // ordinal doesn't exist this month
  return result
}

/**
 * Returns the same-day-next-month Date, used as the far edge of the sync
 * window (e.g. run on the 1st → window ends on next month's 1st; run on the
 * 15th → window ends on next month's 15th). Since this script only ever runs
 * on the 1st or 15th, there's no month-length edge case to worry about here.
 */
function computeWindowEnd(fromDate) {
  const end = new Date(fromDate)
  end.setMonth(end.getMonth() + 1)
  return end
}

/**
 * Returns ALL occurrences of "the Nth <weekday> of the month at H:MM" that
 * fall within [fromDate, untilDate) — not just the next one. Each sync run
 * covers a rolling ~1-month window (see computeWindowEnd), and consecutive
 * runs overlap on purpose: a date generated by one run and re-generated by
 * the next is expected to land on the same source_id and get updated rather
 * than duplicated (source_id includes the date — see locationToPosts).
 * `isBlocked(date)` skips specific cancelled calendar dates.
 */
function allNthWeekdayOccurrencesInWindow(ordinal, weekdayIndex, hour, minute, fromDate, untilDate, isBlocked = () => false) {
  const occurrences = []
  const monthSpan = (untilDate.getFullYear() - fromDate.getFullYear()) * 12
    + (untilDate.getMonth() - fromDate.getMonth()) + 1 // +1 month of buffer for safety

  for (let i = 0; i <= monthSpan; i++) {
    const probe = new Date(fromDate.getFullYear(), fromDate.getMonth() + i, 1)
    const candidate = nthWeekdayOfMonth(probe.getFullYear(), probe.getMonth(), weekdayIndex, ordinal)
    if (!candidate) continue
    candidate.setHours(hour, minute, 0, 0)
    if (candidate <= fromDate) continue
    if (candidate >= untilDate) continue
    if (isBlocked(candidate)) continue
    occurrences.push(candidate)
  }
  return occurrences
}

/** Formats a Date as a compact "YYYYMMDD" key for building stable, date-scoped source_ids. */
function dateKey(date) {
  const y = date.getFullYear()
  const m = String(date.getMonth() + 1).padStart(2, '0')
  const d = String(date.getDate()).padStart(2, '0')
  return `${y}${m}${d}`
}

/**
 * Deterministically parses schedule text made of comma-separated clauses like:
 *   "1st and 3rd Thursday of the month 10:00am, 2nd Tuesday of the month 9:00am - 11:00am"
 *
 * Real SDFB data mixes several phrasings for the same thing, all handled here:
 *   - "of the month" AND "of each month" (used interchangeably)
 *   - "of the month" is sometimes dropped entirely ("4th Thursday from 3:00 PM...")
 *   - start time led by "at", by "from", or by nothing at all
 *   - start/end time separated by a dash OR by the word "to"
 *   - hour-only times with no colon ("11 AM", "9 am - 11 am")
 *   - trailing "until food is gone" / "until food runs out" instead of an end time
 *   - plural weekday names ("1st and 4th Thursdays")
 *
 * Returns { matched: [...], unmatchedText: string }. Each matched entry is
 * { ordinals: [1,3], weekdayIndex, hour, minute, endHour, endMinute, raw }.
 */
function parseOrdinalWeekdaySchedule(scheduleText) {
  const clauseRegex = /^\s*((?:\d+(?:st|nd|rd|th)|first|second|third|fourth|fifth|last)(?:\s*(?:,|and)\s*(?:\d+(?:st|nd|rd|th)|first|second|third|fourth|fifth|last))*)\s+(sunday|monday|tuesday|wednesday|thursday|friday|saturday)s?\s+(?:of (?:the|each) month)?[,;]?\s*(?:from\s+)?(?:at\s+)?(\d{1,2}(?::\d{2})?\s*[AP]M)(?:\s*(?:[-–]|to)\s*(\d{1,2}(?::\d{2})?\s*[AP]M))?\s*(?:(?:or\s+)?until food (?:is gone|runs out))?\s*$/i

  const rawClauses = scheduleText.split(',').map(c => c.trim()).filter(Boolean)
  const matched = []
  const unmatched = []

  for (const clause of rawClauses) {
    const m = clause.match(clauseRegex)
    if (!m) { unmatched.push(clause); continue }

    const ordinalTokens = m[1].split(/\s*(?:,|and)\s*/i).map(t => t.trim().toLowerCase()).filter(Boolean)
    const ordinals = ordinalTokens.map(t => ORDINAL_MAP[t]).filter(o => o !== undefined)
    const weekdayIndex = DAY_INDEX[m[2].toLowerCase()]
    const startTime = parseSingleTime(m[3])
    const endTime = m[4] ? parseSingleTime(m[4]) : null

    if (ordinals.length === 0 || weekdayIndex === undefined || !startTime) {
      unmatched.push(clause)
      continue
    }

    matched.push({
      ordinals,
      weekdayIndex,
      weekdayName: m[2].toLowerCase(),
      hour: startTime.hour,
      minute: startTime.minute,
      endHour: endTime ? endTime.hour : null,
      endMinute: endTime ? endTime.minute : null,
      raw: clause,
    })
  }

  return { matched, unmatchedText: unmatched.join(', ') }
}

/**
 * Extracts specific calendar dates (month + day, optionally year) mentioned
 * anywhere in cancellation text, e.g. "Jan 8", "May 7, 2026". Only meaningful
 * for pure cancellations — see needsAiForReschedule() below for why reschedule
 * text isn't handled this way.
 */
function parseFlaggedDates(text) {
  if (!text) return []
  const regex = /\b(jan|january|feb|february|mar|march|apr|april|may|jun|june|jul|july|aug|august|sep|sept|september|oct|october|nov|november|dec|december)\.?\s+(\d{1,2})(?:,\s*(\d{4}))?\b/gi
  const dates = []
  for (const m of text.matchAll(regex)) {
    dates.push({
      month: MONTH_MAP[m[1].toLowerCase()],
      day: parseInt(m[2]),
      year: m[3] ? parseInt(m[3]) : null,
    })
  }
  return dates
}

/** Checks whether a candidate Date matches any flagged (cancelled) date. */
function isFlaggedDate(date, flaggedDates) {
  return flaggedDates.some(f =>
    date.getMonth() === f.month &&
    date.getDate() === f.day &&
    (f.year === null || date.getFullYear() === f.year)
  )
}

/**
 * True if the text is a clean "nothing to see here" statement — e.g. "No
 * holiday reschedules for 2026", "All distributions will be held on
 * regularly scheduled days" — which is safe to ignore entirely and stay on
 * the deterministic path.
 */
function isNoScheduleChangeText(text) {
  if (!text) return true
  return /^(no\s|all distributions will be held)/i.test(text.trim())
}

/**
 * Decides whether a location's reschedule/cancellation text is too semantically
 * loaded to resolve with simple date-skipping, and should instead go through AI
 * with the full schedule + reschedule text as context.
 *
 * Real examples from your data show two genuinely different things sharing one
 * field:
 *   - "Cancellations: May 7, July 2..." — these dates are skipped outright;
 *     the next regular occurrence is correct. Safe to handle deterministically.
 *   - "Rescheduled to: May 29, Nov 20, Dec 11" — these dates ARE the actual
 *     occurrence for whichever month they replace (e.g. a 4th Friday that fell
 *     on a holiday moved to May 29 instead). Skipping May 29 would be wrong —
 *     it's not a date to avoid, it's the date to use. But matching which
 *     reschedule date belongs to which specific month from text alone isn't
 *     reliable, so rather than guess, the whole location goes to AI, which can
 *     read "the 4th Friday moves to May 29 this month" in context.
 *   - "Cancelled January 2026" / "July Cancelled" — whole-month cancellations
 *     with no specific day, which parseFlaggedDates can't represent at all.
 *     Also needs AI.
 *
 * Clean negations ("No holiday reschedules", "All distributions will be held
 * on regularly scheduled days") are excluded so the common, unremarkable case
 * still gets the more reliable deterministic date math.
 */
function needsAiForReschedule(rescheduleText) {
  if (!rescheduleText) return false
  if (isNoScheduleChangeText(rescheduleText)) return false
  return /reschedul|cancel/i.test(rescheduleText)
}

/**
 * Converts a naive "YYYY-MM-DDTHH:MM:00" string (no offset) — as returned by
 * the AI, meaning America/Los_Angeles local time — into a correct UTC ISO
 * string for storage.
 *
 * Relying on `new Date(str)` alone would be a footgun here: per spec, a
 * date-time string with no offset is parsed in the *local* timezone of the
 * running process, which is only correct because we set TZ=America/Los_Angeles
 * at the top of this file. This function makes that dependency explicit and
 * produces an unambiguous 'Z'-suffixed string so Postgres can't misinterpret
 * it under its own session timezone.
 */
function localIsoToUtcIso(naiveLocalIso) {
  if (!naiveLocalIso) return null
  const d = new Date(naiveLocalIso)
  if (isNaN(d)) return null
  return d.toISOString()
}

/**
 * Calls OpenAI GPT-4o-mini (via built-in fetch, no package needed) to parse a
 * natural-language schedule into every occurrence that falls within the given
 * window — not just the next one, since each sync run needs to populate
 * roughly a month of upcoming events at once (see computeWindowEnd).
 *
 * The tags array is passed as a hint because SDFB includes the day of the week
 * as a tag (e.g. "Thursday"), which helps the model resolve ambiguous schedules.
 *
 * Used only as a fallback when the deterministic ordinal-weekday parser above
 * can't recognize the text — LLMs are unreliable at "Nth weekday of month"
 * calendar arithmetic, so prefer the deterministic parser whenever possible.
 * Costs here are low enough that leaning on this fallback freely (rather than
 * flagging for manual review) is the preferred tradeoff.
 *
 * Returns { parsed: true, occurrences: [{start, end}, ...] } or { parsed: false }.
 */
async function parseScheduleWithAI(scheduleText, locationName, dayHints, rescheduleText, windowStart, windowEnd) {
  if (!process.env.OPENAI_API_KEY) return { parsed: false, occurrences: [] }

  const fmt = d => d.toLocaleDateString('en-US', {
    weekday: 'long', year: 'numeric', month: 'long', day: 'numeric',
    timeZone: 'America/Los_Angeles',
  })
  const today = fmt(new Date())

  const hintLine = dayHints.length
    ? `Day-of-week hints from tags: ${dayHints.join(', ')}`
    : ''

  const closureLine = rescheduleText
    ? `Reschedules/cancellations: "${rescheduleText}"`
    : ''

  const prompt = `You are a precise scheduling assistant for food distribution events.

Today (America/Los_Angeles time): ${today}
Window: from ${fmt(windowStart)} through ${fmt(windowEnd)} (exclusive), America/Los_Angeles time
Location: "${locationName}"
${hintLine}
Schedule: "${scheduleText}"
${closureLine}

List EVERY occurrence of this schedule that falls within the window above (there may be one, several, or none). Rules:
- Return ONLY valid JSON: a JSON array of occurrences, no markdown or explanation
- Each item: {"start":"YYYY-MM-DDTHH:MM:00","end":"YYYY-MM-DDTHH:MM:00"} — all datetimes ISO 8601, local America/Los_Angeles time, no offset
- If the end time is not stated, use null for "end"
- Only include occurrences strictly after "today" above and strictly before the window end
- Convert "10:00am", "9:30 am", "2:00 p.m." etc. correctly to 24-hour format
- Use day-of-week hints to resolve any ambiguity about which day is intended
- If a listed date falls within a stated closure or cancellation period, omit that occurrence entirely
- If a reschedule note gives a specific replacement date for an occurrence in this window, use the replacement date instead of the normally-computed one
- If the schedule text cannot be parsed at all, return {"parsed":false} instead of an array

Example, two occurrences in window: [{"start":"2026-08-06T10:00:00","end":null},{"start":"2026-09-03T10:00:00","end":null}]
Example, none fall in window: []
Example, unparseable: {"parsed":false}`

  try {
    const res = await fetch('https://api.openai.com/v1/chat/completions', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Authorization': `Bearer ${process.env.OPENAI_API_KEY}`,
      },
      body: JSON.stringify({
        model: 'gpt-4o-mini',
        messages: [{ role: 'user', content: prompt }],
        response_format: { type: 'json_object' },
        temperature: 0,
        max_tokens: 2000,
      }),
    })
    const json = await res.json()
    const raw = json.choices[0].message.content
    const parsed = JSON.parse(raw)

    if (Array.isArray(parsed)) return { parsed: true, occurrences: parsed }
    // Some JSON-object-mode APIs wrap arrays in a key; handle that shape too.
    if (parsed && Array.isArray(parsed.occurrences)) return { parsed: true, occurrences: parsed.occurrences }
    return { parsed: false, occurrences: [] }
  } catch (err) {
    console.error('    ⚠️  OpenAI API error:', err.message)
    return { parsed: false, occurrences: [] }
  }
}

/**
 * Calls the AI parser on a piece of schedule text and builds one post per
 * occurrence it finds within the window. Used both as the primary fallback
 * (when the deterministic ordinal-weekday parser can't recognize the text at
 * all) and as the secondary fallback (for leftover text, or when reschedule
 * text has semantics too complex for simple date-skipping).
 *
 * source_id includes the occurrence's date (see dateKey()) so that the same
 * specific occurrence — e.g. "August 6, 2026" — gets the same source_id no
 * matter which sync run (1st-of-month or 15th-of-month) generates it. Since
 * the two runs' ~1-month windows overlap, the same occurrence is often
 * regenerated by both; matching source_ids means the second run updates the
 * existing row instead of creating a duplicate.
 *
 * Returns an array of post payloads (zero, one, or many).
 */
async function buildAiParsedPost(loc, text, dayHints, rescheduleText, sharedDesc, base, sourceIdSuffix, windowStart, windowEnd) {
  console.log(`    🤖 AI parsing: "${text}"`)
  const ai = await parseScheduleWithAI(text, loc.name, dayHints, rescheduleText, windowStart, windowEnd)

  if (!ai.parsed) {
    return [{
      ...base,
      source_id: `${SOURCE_PREFIX}${loc.id}_${sourceIdSuffix}`,
      description: [
        '⚠️ REVIEW REQUIRED — Schedule could not be parsed automatically, even by AI.\n' +
        'Please set the date and time manually before publishing.\n\n' +
        `Raw schedule: ${text}`,
        sharedDesc,
      ].filter(Boolean).join('\n\n'),
      start_time: null,
      end_time: null,
    }]
  }

  // Defensive filter: trust the prompt, but don't let a minor AI boundary
  // mistake create a post outside the intended window.
  const inWindow = ai.occurrences.filter(occ => {
    if (!occ?.start) return false
    const d = new Date(occ.start) // naive local string, interpreted as America/Los_Angeles per TZ set at top of file
    return !isNaN(d) && d > windowStart && d < windowEnd
  })

  if (inWindow.length === 0) {
    // Parsed fine, but nothing falls in this window (e.g. seasonal pause) — informational, not an error.
    return [{
      ...base,
      source_id: `${SOURCE_PREFIX}${loc.id}_${sourceIdSuffix}`,
      description: [`📅 Schedule\n${text}\n\n(No occurrences fall within the current sync window.)`, sharedDesc]
        .filter(Boolean).join('\n\n'),
      start_time: null,
      end_time: null,
    }]
  }

  return inWindow.map(occ => {
    const startIso = localIsoToUtcIso(occ.start)
    const endIso = localIsoToUtcIso(occ.end)
    const key = dateKey(new Date(occ.start))
    return {
      ...base,
      source_id: `${SOURCE_PREFIX}${loc.id}_${sourceIdSuffix}_${key}`,
      description: [`📅 Schedule\n${text}`, sharedDesc].filter(Boolean).join('\n\n'),
      start_time: startIso,
      end_time: endIso,
    }
  })
}


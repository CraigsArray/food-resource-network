/**
 * Converts one Storepoint location into one or more post payloads, covering
 * every occurrence of its schedule within [windowStart, windowEnd).
 *
 * SDFB locations never have structured day/hour Storepoint fields (unlike
 * Feeding SD) — all schedule data lives in the CF_SCHEDULE custom field as
 * text, so every location goes through one of:
 *   A) "Nth <weekday> of the month" text, deterministically parsed → one post
 *      per occurrence per ordinal/weekday/time clause (real date math, no AI
 *      guessing) — a clause can produce multiple posts if the window spans
 *      more than one occurrence of it
 *   B) Anything A doesn't fully recognize (unusual phrasing, leftover text
 *      alongside clauses A did match, or reschedule text too complex for
 *      simple date-skipping) → AI-parsed occurrences, using day-of-week tags
 *      as a disambiguation hint
 *   C) No schedule text at all → one post, flagged for review (nothing to
 *      hand the AI either)
 */
async function locationToPosts(loc, orgId, windowStart, windowEnd) {
  const addr = parseAddress(loc.streetaddress)
  const cf = parseCustomFields(loc.custom_fields)

  const scheduleText = (cf[CF_SCHEDULE] ?? '').trim()
  const rescheduleText = (cf[CF_RESCHEDULES] ?? '').trim()
  const foodType = (cf[CF_FOOD_TYPE] ?? '').trim()
  const eligibility = (cf[CF_ELIGIBILITY] ?? '').trim()
  const instructions = (cf[CF_INSTRUCTIONS] ?? '').trim()

  // Normalise tags and extract day-of-week values as AI hints
  const rawTags = normaliseTags(loc.tags)
  const dayNames = new Set(['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday'])
  const dayHints = rawTags.filter(t => dayNames.has(t))

  // Strip day-of-week tags and internal program codes (e.g. EFAP) — meaningless to public visitors
  const STRIP_TAGS = new Set([...dayNames, 'Efap', 'EFAP', 'efap'])
  const cleanTags = rawTags.filter(t => !STRIP_TAGS.has(t))
  const tags = [...new Set([...cleanTags, 'San Diego Food Bank'])]

  const flaggedDates = parseFlaggedDates(rescheduleText)

  // Shared description sections appended to every post from this location
  const sharedLines = []
  if (foodType) sharedLines.push(`🥕 Food Provided\n${foodType}`)
  if (eligibility) sharedLines.push(`✅ Eligibility\n${eligibility}`)
  if (instructions) sharedLines.push(`ℹ️ Service Instructions\n${instructions}`)
  if (rescheduleText) sharedLines.push(`⚠️ Closures & Reschedules\n${rescheduleText}`)
  const sharedDesc = sharedLines.join('\n\n')

  const base = {
    organization_id: orgId,
    title: loc.name,
    location_name: loc.name,
    address: addr.address,
    city: addr.city,
    zip: addr.zip,
    latitude: loc.loc_lat || null,
    longitude: loc.loc_long || null,
    category: 'food-distribution',
    tags,
    // Phone in its own column so the feed renders it as a tap-to-call link
    organizer_phone: loc.phone?.trim() || null,
    // SD Food Bank logo — same image used in the partner org box on the public feed
    image_url: 'https://www.vikingcold.com/wp-content/uploads/2019/11/san-diego-food-bank.png',
    is_active: true,
    is_recurring: false,
    // Published immediately so posts appear on the live feed after sync
    status: 'published',
  }

  const posts = []

  // ── "Nth <weekday> of the month" — parsed deterministically ────────────────
  if (scheduleText) {
    const { matched, unmatchedText } = parseOrdinalWeekdaySchedule(scheduleText)
    const rescheduleNeedsAi = needsAiForReschedule(rescheduleText)

    if (matched.length > 0 && rescheduleNeedsAi) {
      // The recurring pattern parsed fine, but the reschedule/cancellation text
      // has semantics (a specific replacement date, a whole-month cancellation)
      // that simple date-skipping can't safely resolve — see needsAiForReschedule().
      // Hand the whole thing to AI with full context rather than risk a wrong date.
      console.log(`    🤖 Pattern matched, but reschedule text needs interpretation — sending to AI: "${rescheduleText}"`)
      posts.push(...await buildAiParsedPost(loc, scheduleText, dayHints, rescheduleText, sharedDesc, base, 'custom', windowStart, windowEnd))
      return posts
    }

    if (matched.length > 0) {
      console.log(`    🗓️  Deterministically parsed ${matched.length} schedule clause(s)`)

      for (const clause of matched) {
        for (const ordinal of clause.ordinals) {
          const occurrences = allNthWeekdayOccurrencesInWindow(
            ordinal, clause.weekdayIndex, clause.hour, clause.minute,
            windowStart, windowEnd,
            candidate => isFlaggedDate(candidate, flaggedDates)
          )
          if (occurrences.length === 0) {
            console.log(`    ⚠️  No occurrence for "${ordinal}" ${clause.weekdayName} falls within this window — skipping`)
            continue
          }

          const ordinalLabel = ordinal === 'last' ? 'last' : { 1: '1st', 2: '2nd', 3: '3rd', 4: '4th', 5: '5th' }[ordinal]
          const weekdayLabel = clause.weekdayName.charAt(0).toUpperCase() + clause.weekdayName.slice(1)

          for (const startDt of occurrences) {
            let endDt = null
            if (clause.endHour !== null) {
              endDt = new Date(startDt)
              endDt.setHours(clause.endHour, clause.endMinute, 0, 0)
            }

            const descLines = [`📅 Schedule\nRecurring: ${ordinalLabel} ${weekdayLabel} of the month — ${clause.raw}.`]
            if (sharedDesc) descLines.push(sharedDesc)

            posts.push({
              ...base,
              // Date-scoped so this specific occurrence keeps the same source_id
              // across overlapping sync-run windows (see buildAiParsedPost's comment).
              source_id: `${SOURCE_PREFIX}${loc.id}_${clause.weekdayName}_${ordinalLabel}_${dateKey(startDt)}`,
              description: descLines.join('\n\n'),
              start_time: startDt.toISOString(),
              end_time: endDt ? endDt.toISOString() : null,
            })
          }
        }
      }

      // Leftover text the deterministic parser didn't recognize → AI, not a review flag
      if (unmatchedText) {
        posts.push(...await buildAiParsedPost(loc, unmatchedText, dayHints, rescheduleText, sharedDesc, base, 'custom', windowStart, windowEnd))
      }

      return posts
    }

    // Nothing matched deterministically at all — hand the whole string to AI
    posts.push(...await buildAiParsedPost(loc, scheduleText, dayHints, rescheduleText, sharedDesc, base, 'custom', windowStart, windowEnd))
    return posts
  }

  // ── No schedule text at all — nothing to parse, flag for review ────────────
  const descLines = [
    '⚠️ REVIEW REQUIRED — No schedule information could be determined.\n' +
    'Please set the date and time manually before publishing.',
  ]
  if (sharedDesc) descLines.push(sharedDesc)

  posts.push({
    ...base,
    source_id: `${SOURCE_PREFIX}${loc.id}_custom`,
    description: descLines.join('\n\n'),
    start_time: null,
    end_time: null,
  })
  return posts
}

// ─── Database operations ──────────────────────────────────────────────────────

/**
 * Upserts a single post.
 *
 * Duplicate rules:
 *   1. Same source_id           → update (admin's status and is_active are preserved).
 *   2. Same address + start_time → skip (always a duplicate, regardless of source).
 *
 * Returns: 'new' | 'updated' | 'skipped'
 */
async function upsertPost(post) {

  // ── Duplicate guard: address + start_time collision with a different source ──
  if (post.start_time) {
    const { data: dupe } = await supabase
      .from('posts')
      .select('id, title, source_id')
      .eq('address', post.address)
      .eq('start_time', post.start_time)
      .neq('source_id', post.source_id)
      .maybeSingle()

    if (dupe) {
      console.log(`    ⏩ Skipped — duplicate of "${dupe.title}" (same address + time)`)
      return 'skipped'
    }
  }

  // ── Check for existing record by source_id ──────────────────────────────────
  const { data: existing } = await supabase
    .from('posts')
    .select('id, status, is_active')
    .eq('source_id', post.source_id)
    .maybeSingle()

  if (existing) {
    // UPDATE: refresh data fields but preserve admin's status and is_active decisions.
    const { status, is_active, ...dataFields } = post
    const { error } = await supabase
      .from('posts')
      .update(dataFields)
      .eq('id', existing.id)

    if (error) {
      console.error(`    ✗ Update failed [${post.source_id}]:`, error.message)
      return 'skipped'
    }
    console.log(`    ↻ Updated: ${post.title}`)
    return 'updated'
  }

  // INSERT: brand-new post, always starts as draft
  const { error } = await supabase.from('posts').insert(post)
  if (error) {
    console.error(`    ✗ Insert failed [${post.source_id}]:`, error.message)
    return 'skipped'
  }
  console.log(`    ✨ New post: ${post.title}`)
  return 'new'
}

/** Extracts the Storepoint location id embedded at the start of a source_id. */
function extractLocationId(sourceId) {
  const rest = sourceId.slice(SOURCE_PREFIX.length)
  const idx = rest.indexOf('_')
  return idx === -1 ? rest : rest.slice(0, idx)
}

/**
 * Deactivates SDFB posts that no longer belong on the live feed, for two
 * distinct reasons:
 *
 *   1. VANISHED — the location itself is no longer in the current Storepoint
 *      batch (left the Food Bank's network entirely).
 *
 *   2. STALE — the location still exists, but THIS specific post wasn't
 *      regenerated by the current run, and it isn't simply a past event that
 *      aged out of the window naturally. This catches posts left behind by
 *      an old naming scheme (e.g. `sdfb_<id>` from before source_ids were
 *      date-scoped) that will never be regenerated or updated under the new
 *      scheme, as well as an occurrence that got superseded (e.g. a
 *      cancellation/reschedule that changed which date applies). A post
 *      whose start_time is already in the past relative to this run's window
 *      is left alone — that's expected aging, not staleness.
 */
async function deactivateVanished(processedLocationIds, processedPostIds, windowStart) {
  const { data: activeSdfb, error } = await supabase
    .from('posts')
    .select('id, source_id, title, description, start_time')
    .like('source_id', `${SOURCE_PREFIX}%`)
    .eq('is_active', true)

  if (error) {
    console.error('  ✗ Could not fetch existing SDFB posts:', error.message)
    return 0
  }

  const stale = (activeSdfb ?? []).filter(p => {
    const locationVanished = !processedLocationIds.has(extractLocationId(p.source_id))
    if (locationVanished) return true
    if (processedPostIds.has(p.source_id)) return false // regenerated this run — still current
    if (p.start_time && new Date(p.start_time) < windowStart) return false // already happened — expected aging, not stale
    return true // location is active, but this exact post wasn't regenerated and isn't a past event
  })

  if (stale.length === 0) { console.log('  ✓ No vanished or stale posts.'); return 0 }

  const runDate = new Date().toLocaleDateString('en-US', {
    month: 'long', day: 'numeric', year: 'numeric',
  })

  for (const post of stale) {
    const locationVanished = !processedLocationIds.has(extractLocationId(post.source_id))
    const notice = locationVanished
      ? `[Auto-deactivated ${runDate} — location no longer in San Diego Food Bank's directory.]`
      : `[Auto-deactivated ${runDate} — superseded by updated sync data (old source_id format or a changed occurrence). If this looks wrong, check the location's current schedule.]`
    const { error: err } = await supabase
      .from('posts')
      .update({
        is_active: false,
        description: `${notice}\n\n${post.description ?? ''}`.trim(),
      })
      .eq('id', post.id)

    if (err) console.error(`  ✗ Deactivate failed for "${post.title}":`, err.message)
    else console.log(`  🗑️  Deactivated (${locationVanished ? 'vanished' : 'stale'}): ${post.title} [${post.source_id}]`)
  }

  return stale.length
}

// ─── Main ─────────────────────────────────────────────────────────────────────

async function main() {
  console.log(`\n${'─'.repeat(60)}`)
  console.log(`🔄  San Diego Food Bank sync — ${new Date().toLocaleString()}`)
  console.log(`${'─'.repeat(60)}\n`)

  // Validate required environment variables
  const missing = ['SUPABASE_URL', 'SUPABASE_SERVICE_ROLE_KEY'].filter(k => !process.env[k])
  if (missing.length) {
    console.error('❌  Missing required environment variables:', missing.join(', '))
    process.exit(1)
  }
  if (!process.env.OPENAI_API_KEY) {
    console.warn('⚠️   OPENAI_API_KEY not set — schedules that need AI parsing will be flagged for manual review.\n')
  }

  // ── 1. Look up the San Diego Food Bank org in Supabase ─────────────────────
  console.log(`🏢  Looking up "${ORG_DOMAIN}" organization…`)
  const { data: org, error: orgErr } = await supabase
    .from('organizations')
    .select('id, name')
    .eq('domain', ORG_DOMAIN)
    .single()

  if (orgErr || !org) {
    console.error(`❌  Organization not found for domain "${ORG_DOMAIN}".`)
    console.error('    Run this SQL in Supabase first:')
    console.error(`    INSERT INTO organizations (name, domain, is_verified)`)
    console.error(`    VALUES ('San Diego Food Bank', '${ORG_DOMAIN}', true)`)
    console.error(`    ON CONFLICT (domain) DO UPDATE SET is_verified = true;`)
    process.exit(1)
  }
  console.log(`    Found: "${org.name}" (${org.id})\n`)

  // ── 2. Fetch all locations from Storepoint ──────────────────────────────────
  console.log('📡  Fetching from Storepoint API…')
  const res = await fetch(STOREPOINT_URL)
  if (!res.ok) {
    console.error(`❌  Storepoint API returned HTTP ${res.status}`)
    process.exit(1)
  }
  const { results } = await res.json()
  const allLocations = results?.locations ?? []
  console.log(`    ${allLocations.length} total locations received`)

  // ── 3. Filter to East County ZIP codes ─────────────────────────────────────
  const eastCounty = allLocations.filter(loc => {
    const { zip } = parseAddress(loc.streetaddress)
    return EAST_COUNTY_ZIPS.has(zip)
  })
  console.log(`    ${eastCounty.length} East County locations after ZIP filter\n`)

  // ── 4. Compute the sync window ──────────────────────────────────────────────
  // Every occurrence from right now through one month out gets a post — not
  // just the single next one. Running on the 1st and 15th means these windows
  // overlap by design; the overlap is resolved by upsert (same source_id).
  const windowStart = new Date()
  const windowEnd = computeWindowEnd(windowStart)
  console.log(`🗓️  Sync window: ${windowStart.toLocaleDateString('en-US', { timeZone: 'America/Los_Angeles' })} → ${windowEnd.toLocaleDateString('en-US', { timeZone: 'America/Los_Angeles' })}\n`)

  // ── 5. Process each location ────────────────────────────────────────────────
  const processedLocationIds = new Set(eastCounty.map(loc => String(loc.id)))
  const processedPostIds = new Set()
  const counts = { new: 0, updated: 0, skipped: 0 }

  for (const loc of eastCounty) {
    console.log(`📍  ${loc.name}  (${loc.streetaddress})`)

    let posts
    try {
      posts = await locationToPosts(loc, org.id, windowStart, windowEnd)
    } catch (err) {
      console.error(`    ✗ Error building post for ${loc.name}:`, err.message)
      continue
    }

    if (posts.length === 0) {
      console.log('    ⚠️  No valid slots found — location skipped')
      continue
    }

    for (const post of posts) {
      processedPostIds.add(post.source_id)
      const result = await upsertPost(post)
      counts[result]++
    }
  }

  // ── 6. Deactivate vanished locations ────────────────────────────────────────
  console.log('\n🧹  Checking for vanished locations and stale posts…')
  const deactivated = await deactivateVanished(processedLocationIds, processedPostIds, windowStart)

  // ── 7. Summary ──────────────────────────────────────────────────────────────
  console.log(`\n${'─'.repeat(60)}`)
  console.log('✅  Sync complete\n')
  console.log(`    ${eastCounty.length} East County locations processed`)
  console.log(`    ${processedPostIds.size} total post slots evaluated`)
  console.log(`    ${counts.new}       new draft posts created`)
  console.log(`    ${counts.updated}   existing posts refreshed`)
  console.log(`    ${counts.skipped}   skipped (duplicates or errors)`)
  console.log(`    ${deactivated}      deactivated (vanished locations or stale posts)`)
  console.log(`${'─'.repeat(60)}\n`)
}

main().catch(err => {
  console.error('\n❌  Fatal error:', err)
  process.exit(1)
})